"""
exp_annotation_judge.py — LLM-as-second-annotator for inter-annotator agreement.

Uses GPT-5.5 to independently label a sample of post-hoc annotations from
annotations_clean.jsonl, then computes Cohen's κ against a human label file.

Usage
─────
  # Step 1: generate GPT labels for 50 sampled instructions
  python exp_annotation_judge.py --sample 50 --out results/annotation_judge/gpt_labels.jsonl

  # Run three sampled GPT-labeling trials and print an aggregate table
  python exp_annotation_judge.py --sample 200 --seeds 42 43 44 \
      --out results/annotation_judge/gpt_labels.jsonl

  # Step 2: after filling in human_labels.jsonl (see --export-for-human),
  #         compute Cohen's κ
  python exp_annotation_judge.py \
      --gpt   results/annotation_judge/gpt_labels.jsonl \
      --human results/annotation_judge/human_labels.jsonl \
      --kappa

  # Export blank human-label sheet from the same sample
  python exp_annotation_judge.py \
      --gpt results/annotation_judge/gpt_labels.jsonl \
      --export-for-human results/annotation_judge/human_labels.jsonl

Labels (two independent tasks)
───────────────────────────────
  type    : "local_action" | "subgoal"
              local_action = single immediate action, no downstream goal chain
              subgoal      = action chained to a distinct downstream task
  valid   : "yes" | "no"
              yes = instruction names a concrete Minecraft action and a
                    specific target/object/location or craftable end product
              no  = instruction is generic, underspecified, unsafe, impossible,
                    malformed, or not independently actionable
"""

import argparse
import json
import math
import random
import time
from collections import Counter
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).parent.parent))
from utils import load_openai_key
import openai

MODEL = "gpt-4o"
PROMPT_VERSION = "score_v1"
MAX_COMPLETION_TOKENS = 512
MAX_RETRIES = 3

# ── Paths ─────────────────────────────────────────────────────────────────────

ANNOTATIONS_FILE = Path(__file__).parent.parent / (
    "results/instruction_taxonomy/annotations_clean.jsonl"
)

# ── Prompt ────────────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """\
You are an expert evaluator of natural-language instructions for a Minecraft agent controller.
Instructions are generated by a vision-language model watching the agent's trajectory.
Score each instruction on THREE dimensions. All scores are multiples of 0.1 in [0.0, 1.0].

DIMENSION 1 — quality_score
  How good is this as a training label for behavior cloning?
  Consider: specificity, groundedness in observable Minecraft state, actionability.

  1.0  Perfectly specific and grounded. Names a concrete action, the exact target
       object/material, and optionally location or tool. Zero ambiguity.
       e.g. "Mine iron ore with the stone pickaxe" / "Craft a wooden pickaxe from planks"
  0.7–0.9  Specific action and target, minor missing detail (tool unspecified, location vague).
       e.g. "Chop down a tree" / "Mine stone blocks" / "Swim across the river"
  0.4–0.6  Action is identifiable but target is generic or partially ambiguous.
       e.g. "Mine stone to craft a pickaxe" / "Gather resources from the forest"
  0.1–0.3  Only the action verb is clear; target, location, or tool is missing or too vague.
       e.g. "Move forward" / "Explore the area" / "Gather resources"
  0.0  Completely unactionable: no clear action, entirely ambiguous, impossible, or malformed.
       e.g. "Do something useful" / "dig straight down" / "go there"

DIMENSION 2 — action_match_score
  How precisely does this instruction determine the sequence of LOW-LEVEL Minecraft controls?
  Low-level actions are: move, turn, attack, jump, craft_X, place_X, equip_X.
  A high score means a competent controller can infer the exact button sequence from text alone.

  1.0  Completely determines the action sequence. One clear skill, unambiguous target.
       e.g. "Craft a wooden pickaxe" → open_crafting, place_planks, place_stick, craft
  0.7–0.9  Mostly determined. Minor ambiguity in duration or exact target position.
       e.g. "Mine iron ore with the stone pickaxe" → equip_stone_pickaxe, face_ore, attack
  0.4–0.6  Partially determined. Action is clear but target requires visual search.
       e.g. "Chop wood from trees" → face_tree (visual), attack
  0.1–0.3  Action type is guessable but target/duration/sequence is largely undetermined.
       e.g. "Explore the cave" / "Move toward the goal"
  0.0  No actionable low-level sequence can be inferred from text alone.
       e.g. "Continue" / "Do it again" / "Handle the situation"

DIMENSION 3 — type
  "local_action"  — single immediate action, no explicit downstream goal chain
  "subgoal"       — chains a primary action to a downstream task via "to", "so that", etc.

OUTPUT FORMAT
─────────────
Respond with JSON only — no prose, no markdown fences.
{
  "quality_score": <0.0–1.0 in 0.1 steps>,
  "action_match_score": <0.0–1.0 in 0.1 steps>,
  "type": "<local_action|subgoal>",
  "reason": "<one sentence covering both scores>"
}
"""


def judge_instruction(client: openai.OpenAI, instruction: str) -> dict:
    """Call GPT to label one instruction. Returns parsed label dict."""
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            resp = client.chat.completions.create(
                model=MODEL,
                max_tokens=MAX_COMPLETION_TOKENS,
                response_format={"type": "json_object"},
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": f'Instruction: "{instruction}"'},
                ],
            )
            raw = (resp.choices[0].message.content or "").strip()
            if not raw:
                finish_reason = getattr(resp.choices[0], "finish_reason", "unknown")
                raise ValueError(f"empty response; finish_reason={finish_reason}")
            break
        except (openai.OpenAIError, ValueError) as exc:
            if attempt == MAX_RETRIES:
                return {
                    "type": "unknown",
                    "valid": "unknown",
                    "reason": f"judge failed after {MAX_RETRIES} attempts: {exc}",
                }
            time.sleep(0.5 * attempt)

    if raw.startswith("```"):
        raw = raw.split("```")[1].lstrip("json").strip()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return {"type": "unknown", "valid": "unknown", "reason": raw[:120]}


# ── Cohen's κ ─────────────────────────────────────────────────────────────────

def cohen_kappa(labels_a: list, labels_b: list) -> float:
    """Compute Cohen's κ for two lists of string labels."""
    assert len(labels_a) == len(labels_b), "Label lists must be same length"
    categories = sorted(set(labels_a) | set(labels_b))
    n = len(labels_a)

    # Observed agreement
    p_o = sum(a == b for a, b in zip(labels_a, labels_b)) / n

    # Expected agreement
    p_e = sum(
        (labels_a.count(c) / n) * (labels_b.count(c) / n)
        for c in categories
    )

    if p_e == 1.0:
        return 1.0
    return (p_o - p_e) / (1.0 - p_e)


def interpret_kappa(k: float) -> str:
    if k >= 0.80: return "almost perfect"
    if k >= 0.61: return "substantial"
    if k >= 0.41: return "moderate"
    if k >= 0.21: return "fair"
    return "slight / poor"


def _pct(count: int, n: int) -> float:
    return 100.0 * count / n if n else 0.0


def _mean_std(vals):
    if not vals: return 0.0, 0.0
    m = sum(vals) / len(vals)
    s = math.sqrt(sum((v - m)**2 for v in vals) / max(len(vals) - 1, 1))
    return m, s


def summarize_results(results: list, seed: int, out_path: Path) -> dict:
    type_counts  = Counter(r["gpt_type"] for r in results)
    q_scores     = [r["quality_score"]      for r in results if isinstance(r.get("quality_score"), (int, float))]
    am_scores    = [r["action_match_score"] for r in results if isinstance(r.get("action_match_score"), (int, float))]
    n = len(results)
    q_mean, q_std   = _mean_std(q_scores)
    am_mean, am_std = _mean_std(am_scores)
    return {
        "seed": seed, "n": n,
        "type_counts":        dict(type_counts),
        "local_action_rate":  _pct(type_counts.get("local_action", 0), n),
        "subgoal_rate":       _pct(type_counts.get("subgoal", 0), n),
        "quality_mean":       round(q_mean, 3),
        "quality_std":        round(q_std, 3),
        "action_match_mean":  round(am_mean, 3),
        "action_match_std":   round(am_std, 3),
        "out": str(out_path),
    }


def print_label_summary(summary: dict) -> None:
    n = summary["n"]
    print(f"\n── GPT score summary (seed={summary['seed']}, n={n}) ──")
    for t, c in sorted(summary["type_counts"].items()):
        print(f"  type={t:<15s}: {c:4d}  ({_pct(c, n):.1f}%)")
    print(f"  quality_score     : {summary['quality_mean']:.3f} ± {summary['quality_std']:.3f}")
    print(f"  action_match_score: {summary['action_match_mean']:.3f} ± {summary['action_match_std']:.3f}")
    print(f"\nLabels written to: {summary['out']}")


def print_multi_seed_table(summaries: list) -> None:
    if not summaries:
        return

    print("\n── Multi-seed GPT score summary ──")
    print("| Seed | N | Local action | Subgoal | Quality (mean±std) | Action match (mean±std) |")
    print("|---:|---:|---:|---:|---:|---:|")
    for s in summaries:
        print(
            f"| {s['seed']} | {s['n']} "
            f"| {s['local_action_rate']:.1f}% | {s['subgoal_rate']:.1f}% "
            f"| {s['quality_mean']:.3f} ± {s['quality_std']:.3f} "
            f"| {s['action_match_mean']:.3f} ± {s['action_match_std']:.3f} |"
        )

    q_means  = [s["quality_mean"]      for s in summaries]
    am_means = [s["action_match_mean"] for s in summaries]
    q_m, q_s   = _mean_std(q_means)
    am_m, am_s = _mean_std(am_means)
    print(f"\nPooled quality_score      : {q_m:.3f} ± {q_s:.3f}")
    print(f"Pooled action_match_score : {am_m:.3f} ± {am_s:.3f}")


def out_path_for_seed(out_template: str, seed: int) -> str:
    if "{seed}" in out_template:
        return out_template.format(seed=seed)

    path = Path(out_template)
    if path.suffix:
        return str(path.with_name(f"{path.stem}_seed{seed}{path.suffix}"))
    return str(path / f"gpt_labels_seed{seed}.jsonl")


# ── Main steps ────────────────────────────────────────────────────────────────

def run_judge(args):
    """Step 1: generate GPT labels for a random sample."""
    load_openai_key()
    client = openai.OpenAI()

    # Load all annotations and sample
    all_anns = []
    with open(ANNOTATIONS_FILE) as f:
        for line in f:
            all_anns.append(json.loads(line))

    random.seed(args.seed)
    sample = random.sample(all_anns, min(args.sample, len(all_anns)))
    print(f"Sampled {len(sample)} instructions from {len(all_anns)} total.")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    existing_by_id = {}
    done_ids = set()
    if out_path.exists() and not args.overwrite:
        with open(out_path) as f:
            for line in f:
                if not line.strip():
                    continue
                record = json.loads(line)
                existing_by_id[record["id"]] = record
        for record in existing_by_id.values():
            if (
                record.get("judge_prompt_version") == PROMPT_VERSION
                and record.get("gpt_type") != "unknown"
                and record.get("quality_score", -1) >= 0.0
                and record.get("action_match_score", -1) >= 0.0
            ):
                done_ids.add(record["id"])
        if done_ids:
            print(f"Resuming from {out_path}; found {len(done_ids)} existing labels.")
        retry_ids = set(existing_by_id) - done_ids
        if retry_ids:
            print(f"Re-labeling {len(retry_ids)} stale, unknown, or failed labels.")

    results = []
    with open(out_path, "w") as f:
        for i in range(len(sample)):
            if i in done_ids:
                record = existing_by_id[i]
                results.append(record)
                f.write(json.dumps(record) + "\n")
        f.flush()

        for i, ann in enumerate(sample):
            if i in done_ids:
                continue

            instr = ann["instruction"]
            label = judge_instruction(client, instr)
            def _clamp_score(v):
                try:
                    v = round(float(v) * 10) / 10   # snap to 0.1 grid
                    return max(0.0, min(1.0, v))
                except (TypeError, ValueError):
                    return -1.0   # sentinel for parse failure

            record = {
                "id": i,
                "env": ann["env"],
                "u": ann["u"],
                "v": ann["v"],
                "instruction": instr,
                "quality_score":      _clamp_score(label.get("quality_score", -1)),
                "action_match_score": _clamp_score(label.get("action_match_score", -1)),
                "gpt_type":           label.get("type", "unknown"),
                "gpt_reason":         label.get("reason", ""),
                "judge_prompt_version": PROMPT_VERSION,
            }
            results.append(record)
            f.write(json.dumps(record) + "\n")
            f.flush()

            print(f"  [{i+1:3d}/{len(sample)}] {instr[:55]:<55}  "
                  f"Q={record['quality_score']:.1f}  AM={record['action_match_score']:.1f}"
                  f"  [{record['gpt_type']}]")
            time.sleep(0.05)

    summary = summarize_results(results, args.seed, out_path)
    print_label_summary(summary)
    return summary


def run_multi_seed(args):
    """Run GPT labels for multiple seeds and print an aggregate table."""
    summaries = []
    for seed in args.seeds:
        seed_args = argparse.Namespace(**vars(args))
        seed_args.seed = seed
        seed_args.out = out_path_for_seed(args.out, seed)
        print(f"\n========== Seed {seed} → {seed_args.out} ==========")
        summaries.append(run_judge(seed_args))

    print_multi_seed_table(summaries)


def export_for_human(args):
    """Export a blank CSV-style JSONL for human labeling."""
    claude_path = Path(args.gpt)
    out_path = Path(args.export_for_human)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    with open(claude_path) as f:
        records = [json.loads(l) for l in f]

    with open(out_path, "w") as f:
        for r in records:
            human_record = {
                "id": r["id"],
                "instruction": r["instruction"],
                "human_type": "",    # fill in: local_action | subgoal
                "human_valid": "",   # fill in: yes | no
            }
            f.write(json.dumps(human_record) + "\n")

    print(f"Blank human-label sheet written to: {out_path}")
    print("Fill in 'human_type' and 'human_valid' for each entry, then run --kappa.")


def compute_kappa(args):
    """Step 2: load GPT + human labels and compute Cohen's κ."""
    with open(args.gpt) as f:
        gpt_records = {r["id"]: r for r in (json.loads(l) for l in f)}
    with open(args.human) as f:
        human_records = {r["id"]: r for r in (json.loads(l) for l in f)}

    # Align on shared IDs with complete labels
    shared_ids = sorted(
        i for i in gpt_records
        if i in human_records
        and human_records[i].get("human_type") not in ("", None)
        and human_records[i].get("human_valid") not in ("", None)
        and gpt_records[i].get("gpt_type") not in ("unknown",)
        and gpt_records[i].get("gpt_valid") not in ("unknown",)
    )
    n = len(shared_ids)
    if n == 0:
        print("No complete label pairs found. Fill in human_labels.jsonl first.")
        return

    gpt_type    = [gpt_records[i]["gpt_type"]      for i in shared_ids]
    human_type  = [human_records[i]["human_type"]  for i in shared_ids]
    gpt_valid   = [gpt_records[i]["gpt_valid"]     for i in shared_ids]
    human_valid = [human_records[i]["human_valid"] for i in shared_ids]

    k_type  = cohen_kappa(gpt_type, human_type)
    k_valid = cohen_kappa(gpt_valid, human_valid)

    obs_type  = sum(a == b for a, b in zip(gpt_type, human_type)) / n
    obs_valid = sum(a == b for a, b in zip(gpt_valid, human_valid)) / n

    print(f"\n── Inter-annotator agreement (n={n}) ──")
    print(f"  Instruction type  : κ = {k_type:.3f}  ({interpret_kappa(k_type)})"
          f"   observed={obs_type:.1%}")
    print(f"  Instruction valid : κ = {k_valid:.3f}  ({interpret_kappa(k_valid)})"
          f"   observed={obs_valid:.1%}")

    print(f"\n── Disagreements on 'type' ──")
    for i in shared_ids:
        gt, ht = gpt_records[i]["gpt_type"], human_records[i]["human_type"]
        if gt != ht:
            print(f"  id={i:3d}  gpt={gt:<14s} human={ht:<14s}  "
                  f"\"{gpt_records[i]['instruction'][:60]}\"")

    summary = {
        "n": n,
        "kappa_type": round(k_type, 4),
        "kappa_valid": round(k_valid, 4),
        "observed_agreement_type": round(obs_type, 4),
        "observed_agreement_valid": round(obs_valid, 4),
        "interpretation_type": interpret_kappa(k_type),
        "interpretation_valid": interpret_kappa(k_valid),
    }
    out_path = Path(args.gpt).parent / "kappa_summary.json"
    with open(out_path, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\nSummary written to: {out_path}")


# ── CLI ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sample", type=int, default=50,
                        help="Number of instructions to sample (default: 50)")
    parser.add_argument("--seed", type=int, default=42,
                        help="Random seed for sampling (default: 42)")
    parser.add_argument("--seeds", type=int, nargs="+",
                        help="Run multiple seeds and print an aggregate table")
    parser.add_argument("--out", default="results/annotation_judge/gpt_labels.jsonl",
                        help=("Output path for GPT labels. With --seeds, '{seed}' is "
                              "formatted if present; otherwise _seedN is appended."))
    parser.add_argument("--overwrite", action="store_true",
                        help="Overwrite --out instead of resuming from existing labels")
    parser.add_argument("--gpt", default="results/annotation_judge/gpt_labels.jsonl",
                        help="Path to GPT labels file (for --kappa / --export-for-human)")
    parser.add_argument("--human", default="results/annotation_judge/human_labels.jsonl",
                        help="Path to human labels file (for --kappa)")
    parser.add_argument("--kappa", action="store_true",
                        help="Compute Cohen's κ between GPT and human labels")
    parser.add_argument("--export-for-human", metavar="PATH",
                        help="Export blank human-label sheet from GPT labels")

    args = parser.parse_args()

    if args.kappa:
        compute_kappa(args)
    elif args.export_for_human:
        export_for_human(args)
    elif args.seeds:
        run_multi_seed(args)
    else:
        run_judge(args)


if __name__ == "__main__":
    main()
